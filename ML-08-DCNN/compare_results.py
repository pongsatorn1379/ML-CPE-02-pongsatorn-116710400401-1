import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def save_comparison(results, output_dir):
    """Save a table and accuracy plot for experiments completed in this run."""
    output_dir.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(14, max(5, len(results) * 0.35)))
    names = list(dict.fromkeys(row[0] for row in results))
    for name in names:
        rows = sorted((row for row in results if row[0] == name), key=lambda row: row[1])
        axes[0].plot([row[1] for row in rows], [row[4] * 100 for row in rows], marker="o", label=name)
    axes[0].set(xlabel="Epochs", ylabel="Test accuracy (%)", title="Model comparison", ylim=(0, 105))
    axes[0].legend()
    axes[0].grid(alpha=0.3)
    axes[1].axis("off")
    cells = [[name, epochs, f"{va:.1%}", f"{ta:.1%}", f"{seconds:.1f}"]
             for name, epochs, va, vl, ta, tl, seconds in results]
    table = axes[1].table(cellText=cells, colLabels=["Model", "Epochs", "Val Acc", "Test Acc", "Seconds"],
                          colWidths=[0.34, 0.13, 0.18, 0.18, 0.17], cellLoc="center", loc="center")
    table.auto_set_font_size(False)
    table.set_fontsize(9)
    table.scale(1, 1.5)
    axes[1].set_title("Completed experiments")
    fig.tight_layout()
    fig.savefig(output_dir / "comparison.png", dpi=150)
    plt.close(fig)


def save_best_model(results, output_dir):
    """Save an image describing the winner selected with validation scores."""
    output_dir.mkdir(parents=True, exist_ok=True)
    name, epochs, va, vl, ta, tl, seconds = max(results, key=lambda row: (row[2], -row[3]))
    rows = [["Model", name], ["Epochs", str(epochs)],
            ["Validation accuracy", f"{va:.2%}"], ["Validation loss", f"{vl:.4f}"],
            ["Test accuracy", f"{ta:.2%}"], ["Test loss", f"{tl:.4f}"],
            ["Training time", f"{seconds:.1f} seconds"]]
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.axis("off")
    ax.set_title("Best model", fontsize=18, pad=20)
    table = ax.table(cellText=rows, cellLoc="left", colWidths=[0.5, 0.5], loc="center")
    table.auto_set_font_size(False)
    table.set_fontsize(12)
    table.scale(1, 1.8)
    fig.text(0.5, 0.05, "Selected by validation accuracy; lowest validation loss breaks ties.",
             ha="center", fontsize=10)
    fig.tight_layout(rect=[0, 0.08, 1, 1])
    fig.savefig(output_dir / "best_model.png", dpi=150)
    plt.close(fig)


